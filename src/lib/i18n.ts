export const dictionaries: Record<Locale, Dict> = { pt, en, es };

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
}

export const useLocale = create<LocaleState>()((set) => ({
  locale: "pt",
  setLocale: () => set({ locale: "pt" }),
}));

type Path = string;

function resolve(dict: unknown, path: Path): string | undefined {
  let node: unknown = dict;
  for (const key of path.split(".")) {
    if (typeof node !== "object" || node === null) return undefined;
    node = (node as Record<string, unknown>)[key];
  }
  return typeof node === "string" ? node : undefined;
}

export function useT() {
  const locale = useLocale((s) => s.locale);
  return (path: Path): string => resolve(dictionaries[locale], path) ?? resolve(pt, path) ?? path;
}

export function useLocaleValue<T>(values: Record<Locale, T>): T {
  return values[useLocale((s) => s.locale)];
}
